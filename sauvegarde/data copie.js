// Get looks for a collection
function getLooksByCollection(collectionId) {
    const files = ARCHIVE_FILES[collectionId];
    if (!files) return [];
    
    return files.map((path, index) => ({
        lookNumber: index + 1,
        image: path,
        collection: collectionId
    }));
}

// Get theme images
function getThemeImages(themeId) {
    const files = MOOD_FILES[themeId];
    if (!files) return [];
    
    return files.map((path, index) => ({
        number: index + 1,
        path: path
    }));
}

